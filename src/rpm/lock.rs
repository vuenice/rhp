use std::fs;
use std::path::Path;

use serde::{Deserialize, Serialize};

use super::error::{Result, RpmError};

pub const LOCK_FILENAME: &str = "rpm.lock";

/// Locked dependency graph (`rpm.lock`), guaranteeing reproducible builds.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Lockfile {
    pub version: u32,
    #[serde(default, rename = "package")]
    pub packages: Vec<LockedPackage>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct LockedPackage {
    pub name: String,
    pub version: String,
    #[serde(default)]
    pub source: Option<String>,
    #[serde(default)]
    pub checksum: Option<String>,
    #[serde(default)]
    pub dependencies: Vec<String>,
}

impl Default for Lockfile {
    fn default() -> Self {
        Self {
            version: 1,
            packages: Vec::new(),
        }
    }
}

impl Lockfile {
    pub fn new() -> Self {
        Self::default()
    }

    /// Load and parse lockfile from file path.
    pub fn load_from_file(path: &Path) -> Result<Self> {
        if !path.exists() {
            return Ok(Self::new());
        }
        let content = fs::read_to_string(path)?;
        let lock: Lockfile = toml::from_str(&content).map_err(|e| RpmError::LockfileError {
            path: path.to_path_buf(),
            message: e.to_string(),
        })?;
        Ok(lock)
    }

    /// Serialize and write lockfile to disk with header comment matching cargo.lock format.
    pub fn save_to_file(&self, path: &Path) -> Result<()> {
        let serialized = toml::to_string_pretty(self).map_err(|e| RpmError::LockfileError {
            path: path.to_path_buf(),
            message: e.to_string(),
        })?;
        let output = format!(
            "# This file is automatically @generated by rpm.\n# It is not intended for manual editing.\nversion = {}\n\n{}",
            self.version,
            // Strip any duplicate top-level version if present in serialized output
            if serialized.starts_with("version = ") {
                let mut lines = serialized.lines();
                let _ = lines.next(); // skip version line
                let rest: Vec<&str> = lines.collect();
                rest.join("\n").trim_start().to_string()
            } else {
                serialized
            }
        );
        fs::write(path, output)?;
        Ok(())
    }

    /// Find a locked package by name.
    pub fn find_package(&self, name: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.name == name)
    }

    /// Insert or update a package entry.
    pub fn upsert_package(&mut self, pkg: LockedPackage) {
        if let Some(pos) = self.packages.iter().position(|p| p.name == pkg.name) {
            self.packages[pos] = pkg;
        } else {
            self.packages.push(pkg);
        }
        self.packages.sort_by(|a, b| a.name.cmp(&b.name));
    }

    /// Remove a package entry by name.
    pub fn remove_package(&mut self, name: &str) -> bool {
        let initial_len = self.packages.len();
        self.packages.retain(|p| p.name != name);
        self.packages.len() < initial_len
    }

    /// Extract commit hash from source field if formatted as `git+...#<commit>`
    pub fn get_locked_commit(&self, name: &str) -> Option<String> {
        let pkg = self.find_package(name)?;
        let src = pkg.source.as_deref()?;
        src.rsplit_once('#').map(|(_, commit)| commit.to_string())
    }
}
